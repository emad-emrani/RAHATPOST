CREATE TABLE IF NOT EXISTS city_residents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resident_number INT UNIQUE NOT NULL,
  username TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,
  neighborhood TEXT DEFAULT 'وسط المدينة',
  tier TEXT DEFAULT 'founder',
  house_style TEXT DEFAULT 'modern',
  grid_x INT NOT NULL,
  grid_y INT NOT NULL,
  social_platform TEXT DEFAULT 'app',
  is_visible BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS city_landmarks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  subtitle TEXT,
  landmark_type TEXT DEFAULT 'mosque',
  sponsor_url TEXT,
  badge_text TEXT,
  grid_x INT NOT NULL,
  grid_y INT NOT NULL,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS city_settings (
  id INT PRIMARY KEY DEFAULT 1,
  last_update_text TEXT DEFAULT 'اليوم',
  next_update_text TEXT DEFAULT 'بعد يومين',
  default_view_mode TEXT DEFAULT '3D',
  max_founders INT DEFAULT 1000,
  announcement_text TEXT DEFAULT 'أهلاً بكم في مدينة رهط بوست التفاعلية! لكل متابع ومشترك بيت باسمه.'
);

